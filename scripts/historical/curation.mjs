/**
 * What historical-basemaps' units are called on our maps, year by year.
 *
 * The source's borders are used as they are, but many of its names are not of the year: a 1914
 * colony under the name of the country it became ("Botswana" for Bechuanaland), a state named
 * after the one it replaced ("Manchu Empire" in 1914, two years into the Republic of China), a
 * land shown on its own that was then part of another (Armenia, Georgia and Azerbaijan in the
 * Russian Empire of 1914; Pakistan and Bangladesh in British India in 1945). So:
 *
 *   - `names` gives a unit its name in that year; a colony is "Name (Ruler)", as the source
 *     itself writes "Madagascar (France)". Several source units given one name become one unit —
 *     that is how British India, French West Africa and the 1914 Russian Empire are joined.
 *   - `drop` removes units that no longer existed in that year (the Hejaz in 1938, part of Saudi
 *     Arabia since 1932). Their land goes to the units beside them.
 *   - `carve` adds a unit the source does not draw, or land to one it does, from the outline of
 *     another year's unit (the source also has 1930, read only for this):
 *     `from` that outline, less each of `minus`, kept `within` one of this year's units. The 1938
 *     source has no Kingdom of Yemen (its "Yemen" is the Aden Protectorate again); the 1945 one's
 *     Yemen less 1938's Aden is it.
 *   - `prefer` settles where two units overlap: by default the larger keeps the land; here the
 *     named unit does — British East Africa keeps Jubaland, which the source also gives Somalia.
 *   - `moves` gives, within one modern country (`base`), a unit's land — or all of it, with no
 *     `from` — to another: where the source has a border of another year (East Thrace in
 *     Bulgaria in 1914, as before the Second Balkan War), leaves out a state the modern map draws
 *     exactly (Monaco, Transjordan), or draws a coast in the wrong country (Corsica in Italy).
 *
 * `carve` can also take its outline from Natural Earth's admin-1 provinces, `['admin1', codes]`,
 * where no historical map draws the land at all.
 *
 * And `ISLANDS`: small territories the source leaves out entirely, which would otherwise appear
 * under today's names — Vanuatu in 1914 was the New Hebrides — named here with their ruler.
 *
 * From general historical knowledge, kept to well-established facts; where a year falls in a
 * transition (1945, after the war) the state at the end of the year is shown.
 */

