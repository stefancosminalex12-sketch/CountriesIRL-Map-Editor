/**
 * Regenerates `src/geo/supplementalGeometry.ts` from Natural Earth's admin-0 file.
 *
 * A maintenance script, NOT part of the build: it reaches the network, so it is run
 * by hand. Ordinary builds only read the generated module, which is committed.
 *
 *   node scripts/fetch-country-fixes.mjs
 *
 * Why this exists: `world-atlas` derives its country layer from Natural Earth but
 * simplifies and merges it, and some countries lose whole islands on the way. Bahrain
 * is the clearest case — the authoritative admin-0 file gives it seven polygons
 * totalling 689 km², while world-atlas keeps only the 586 km² main island. The
 * missing pieces include Muharraq, Umm an Nasan and the entire Hawar group, which
 * sits against Qatar's west coast, so their absence is what leaves that stretch of
 * the Gulf looking empty.
 *
 * The geometry written here is Natural Earth's own, at 10m resolution, unmodified
 * apart from coordinate rounding. Nothing is hand-drawn and nothing is reshaped.
 */
import { writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const SOURCE =
  'https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_10m_admin_0_countries.geojson'

/** Countries to lift from admin-0, by ISO alpha-3. */
const COUNTRIES = ['BHR']

const COORD_PRECISION = 4

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const outPath = resolve(root, 'src/geo/supplementalGeometry.ts')

const round = (n) => Number(n.toFixed(COORD_PRECISION))

const response = await fetch(SOURCE)
if (!response.ok) throw new Error(`${SOURCE} -> ${response.status}`)
const source = await response.json()

const blocks = []
for (const code of COUNTRIES) {
  const feature = source.features.find(
    (f) => f.properties.ISO_A3 === code || f.properties.ADM0_A3 === code,
  )
  if (!feature) throw new Error(`${code} not found in admin-0`)

  const polygons =
    feature.geometry.type === 'Polygon'
      ? [feature.geometry.coordinates]
      : feature.geometry.coordinates

  // Largest first, so the main island leads and the representative-point logic
  // downstream picks it without needing to re-sort.
  polygons.sort((a, b) => b[0].length - a[0].length)

  const body = polygons
    .map(
      (polygon) =>
        '    [\n' +
        polygon
          .map(
            (ring) =>
              '      [' +
              ring.map(([lon, lat]) => `[${round(lon)},${round(lat)}]`).join(', ') +
              '],',
          )
          .join('\n') +
        '\n    ],',
    )
    .join('\n')

  let points = 0
  for (const polygon of polygons) for (const ring of polygon) points += ring.length

  blocks.push(
    `/** ${code}: ${polygons.length} polygons, ${points} points, from Natural Earth 10m admin-0. */\n` +
      `export const ${code}_POLYGONS: Position[][][] = [\n${body}\n]`,
  )
  console.log(`[fetch-country-fixes] ${code}: ${polygons.length} polygons, ${points} points`)
}

const file = `/**
 * Generated by scripts/fetch-country-fixes.mjs — do not edit by hand.
 *
 * Verbatim Natural Earth 10m admin-0 geometry for countries whose shape is lost in
 * the simplified country layer. Coordinates are rounded to ${COORD_PRECISION} decimal places
 * (about 11 m) and otherwise unaltered: nothing here is drawn, reshaped or scaled.
 *
 * Source: ${SOURCE}
 */
import type { Position } from 'geojson'

${blocks.join('\n\n')}
`

writeFileSync(outPath, file)
console.log(`[fetch-country-fixes] wrote ${(file.length / 1024).toFixed(1)}kB -> src/geo/supplementalGeometry.ts`)
